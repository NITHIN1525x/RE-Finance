def previous_baseline(current):
    """The newest history version below the current one (v4 -> history/v3/<run>), or None."""
    n = int(str(current.get("version", "v0")).lstrip("v") or 0)
    for v in range(n - 1, 0, -1):
        runs = [p.parent for p in (EVALS / "baseline" / "history" / f"v{v}").glob("*/results.json")]
        if runs:
            return runs[0]
    return None


def structured_group(check_def, result):
    if check_def is None:
        return "report"
    if check_def.get("path") and check_def["path"][0] == "data_quality":
        return "reconciliation"
    expected = result.get("expected")
    is_number = isinstance(expected, (int, float)) and not isinstance(expected, bool)
    return "numeric" if check_def["type"] in ("value", "count") and is_number else "report"


GROUPS = [("execution", "Execution (the skill really ran, wrote its files, changed nothing else)"),
          ("numeric", "Numeric checks (values vs facts from raw workbook cells)"),
          ("reconciliation", "Reconciliation checks (stated subtotals vs detail rows, data-quality warnings)"),
          ("report", "Report-content checks (labels, flags and wording in the generated report)"),
          ("provenance", "Number provenance (P1: every number in the commentary appears in the run's output)"),
          ("commentary", "Commentary claims (graded by a separate model)")]


def grouped_checks(run_case, case_def):
    defs = {c["id"]: c for c in (case_def or {}).get("structured", [])}
    groups = {g: [] for g, _ in GROUPS}
    groups["execution"] = run_case.get("execution", [])
    groups["provenance"] = run_case.get("provenance", [])
    groups["commentary"] = run_case.get("commentary", [])
    for r in run_case.get("structured", []):
        groups[structured_group(defs.get(r["id"]), r)].append(r)
    return groups


def short(v, n=60):
    s = v if isinstance(v, str) else json.dumps(v, default=str)
    return s if len(s) <= n else s[:n - 1] + "…"


