# ------------------------------------------------------------------------------------------------ shared helpers
def publish(path, build):
    """Write build()'s text to path atomically. If build() raises, the previous file is left untouched."""
    text = build()
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-", suffix=".md")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise
    return path


def rel(p):
    try:
        return Path(p).resolve().relative_to(REPO).as_posix()
    except ValueError:
        return Path(p).name


def cell(text):
    """Make a value safe inside a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def rate(statuses):
    """(passed, executed) counting only checks that actually ran."""
    ran = [s for s in statuses if s in EXECUTED]
    return sum(s == "PASS" for s in ran), len(ran)


def fmt_rate(statuses):
    passed, ran = rate(statuses)
    return f"{passed}/{ran} ({passed / ran:.0%})" if ran else "none executed"


def money(x):
    return f"{x:,.2f}"


