    out += ["", "## Comparison with the previous baseline", ""]
    if prev is None:
        out.append("No earlier baseline to compare with.")
    else:
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            compare_runs.main(prev, run_dir)
        out += [f"Output of `python evals/compare_runs.py {rel(prev)} {rel(run_dir)}`:", "", "```", buf.getvalue().strip(), "```"]
    out += ["", "## Known limits (from `evals/README.md`)", "", known_limits(), ""]
    return "\n".join(out)


