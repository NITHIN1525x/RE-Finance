def case_files(cases):
    """[(task number, case)] in cases.json order: Task 3.1 = the first case (a), 3.2 = b, ..."""
    return [(n, case) for n, case in enumerate(cases["cases"], 1)]


def expected_text(check, facts, tol_name):
    if "fact" in check:
        value = fmt_fact(facts[check["fact"]]["value"])
        value = f"{value}%" if tol_name == "percent" else value
    else:
        value = None
    t = check["type"]
    if t == "count":
        where = f" where {json.dumps(check['where'])}" if "where" in check else ""
        return f"count{where} = {value if value is not None else check.get('expected')}"
    if t in ("flag_regex", "md_regex"):
        place = "a flag message" if t == "flag_regex" else "the Markdown report"
        return f"{'present' if check['present'] else 'absent'} in {place}: `{check['pattern']}`"
    if t == "regex":
        return f"matches `{check['pattern']}`"
    if t == "all_field":
        return f"every `{check['field']}` is one of {json.dumps(check['allowed'])}"
    return value if value is not None else json.dumps(check.get("expected"))


def tolerance_text(check, tolerances):
    name = check.get("tol")
    if name == "currency":
        return f"± {tolerances['currency']}"
    if name == "percent":
        return f"± {tolerances['percent']} pp"
    if isinstance(name, (int, float)):
        return f"± {name}"
    return "exact"


def source_text(check, facts):
    if "fact" in check:
        f = facts[check["fact"]]
        return f"{f['sheet']}!{', '.join(f['cells'])}: {f['formula']}"
    if check["type"] in ("flag_regex", "md_regex", "regex"):
        return "the report's own text"
    return "stated in the case"


def json_path(check):
    if not check.get("path"):
        return "-"
    return ".".join(json.dumps(p, separators=(",", ":")) if isinstance(p, dict) else str(p) for p in check["path"])


