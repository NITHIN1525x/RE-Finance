    lines += [f"| {r['status']} | {cell(r['check'])} | {cell(r.get('detail', ''))} |" for r in evidence["results"]]
    lines += ["", "Refresh (live, free, no Claude call): `python scripts/build_submission.py --live-task1`. "
              "The file is replaced only when the run succeeds.", ""]
