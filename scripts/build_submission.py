def backend_python():
    win = REPO / "connection/backend/.venv/Scripts/python.exe"
    return win if win.is_file() else REPO / "connection/backend/.venv/bin/python"


def build_task1_live(client):
    target = SUBMISSION / "Task 1 response.md"
    with tempfile.TemporaryDirectory() as tmp:
        ev_path = Path(tmp) / "evidence.json"
        proc = subprocess.run([str(backend_python()), str(REPO / "connection/scripts/smoke_test"), "--client", client,
                               "--evidence", str(ev_path)], cwd=REPO)
        if not ev_path.is_file():
            raise ValueError(f"smoke test wrote no evidence (exit {proc.returncode}); keeping the previous file")
        evidence = json.loads(ev_path.read_text(encoding="utf-8"))
    return publish(target, lambda: task1_doc(evidence, proc.returncode))


# ------------------------------------------------------------------------------------------------ main
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--live-task1", action="store_true", help="LIVE: refresh Task 1 from the QuickBooks sandbox")
    ap.add_argument("--task2-source", help="explicit *-trends.md for Task 2")
    ap.add_argument("--run", help="eval run directory for Task 3 response")
    ap.add_argument("--client", default="abc-inc-sandbox")
    args = ap.parse_args(argv)

    failures = 0
    if args.live_task1:
        jobs = [("Task 1 response (LIVE)", lambda: [build_task1_live(args.client)])]
    else:
        t1 = SUBMISSION / "Task 1 response.md"
        hit = re.search(r"Run at (\S+)", t1.read_text(encoding="utf-8")) if t1.is_file() else None
        print(f"Task 1 response: live only, not touched ({'last refreshed ' + hit.group(1) if hit else 'not generated yet'}; "
              "refresh with --live-task1)")
        jobs = [("Task 2 response + PDF", lambda: build_task2_both(args.task2_source)),
                ("Task 3.1-3.7", build_task3_cases),
                ("Task 3 response", lambda: [build_task3_response(args.run)])]
    for name, job in jobs:
        try:
            paths = job()
            print(f"{name}: wrote {', '.join(rel(p) for p in paths)}")
        except Exception as exc:  # noqa: BLE001  (report and keep the previous file)
            failures += 1
            print(f"{name}: NOT updated, previous file kept. {type(exc).__name__}: {exc}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
